/**
 * Static OpenCode Go & Zen model catalog data.
 *
 * Pure data, no behavior: the canonical per-model specifications the patch
 * ships as its offline shim. Split out of `models-catalog.ts` so the parsing,
 * SWR revalidation and gateway enrichment logic reads without wading through
 * several hundred lines of literals.
 *
 * Prices are USD per million tokens. `models.opencode.ai/api.json` remains the
 * live source of truth; this shim is what the meter and picker use before the
 * first successful revalidation (and if it never succeeds).
 *
 * **GENERATED — do not hand-edit.** `scripts/regenerate-catalog-shim.ts` writes
 * both arrays from `parseModelsDevCatalog`, the plugin's own parser, so the shim
 * cannot disagree with what a live refresh produces. Run it and commit the diff:
 *
 * ```sh
 * node --experimental-strip-types scripts/regenerate-catalog-shim.ts --write
 * ```
 *
 * It drifted once already, and the damage was invisible from here: `provider_npm`
 * was added to the parser and to exactly one entry by hand, so every other model
 * naming an SDK was routed to an endpoint that does not speak its format — a
 * model that is *present but wrong* fails with a gateway error reading like a
 * model problem, where a model that is merely *absent* simply waits for the first
 * refresh. That asymmetry is why the shim is complete rather than curated.
 *
 * @module dsh-opencode-patch/catalog-data
 */

import type { ModelCostRate } from "./session-cost.ts";

/**
 * One way a model accepts a thinking/reasoning setting.
 *
 * `models.dev` describes these as a discriminated list; only the fields it
 * actually sends are modelled, and an unknown `type` is dropped rather than
 * guessed at.
 */
export interface ReasoningOptionSpec {
  min?: number;
  type: string;
  values?: readonly string[];
}

export interface CatalogModelSpec {
  context_window: number;
  cost?: ModelCostRate;
  id: string;
  input_modalities: string[];
  is_free?: boolean;
  /**
   * Whether the model accepts a thinking/reasoning setting at all, and which
   * kind - `models.dev` carries it as a boolean plus an options list. The three
   * shapes seen live are `{type:"effort",values:[…]}`, `{type:"budget_tokens",
   * min}`, and `{type:"toggle"}`.
   *
   * The shim dropped both fields, so a picker built from it could not offer a
   * thinking level for any model: 117 of 122 Zen models declare `reasoning` and
   * none of them reached the plugin.
   */
  reasoning?: boolean;
  reasoning_options?: readonly ReasoningOptionSpec[];
  max_output_tokens: number;
  name: string;
  /**
   * The SDK this model needs, present only when it differs from the provider's
   * default.
   *
   * models.dev sets `provider.npm` as an OVERRIDE: `opencode`'s provider-level
   * value is `@ai-sdk/openai-compatible`, so the 53 models carrying no override
   * speak that, while the 32 carrying `@ai-sdk/openai` are served on the
   * Responses API and the 23 carrying `@ai-sdk/anthropic` on Messages. That is
   * the vendor's own statement of the split, which is why `responses-routes.ts`
   * dispatches on it rather than on a list we would have to maintain.
   */
  provider_npm?: string;
}


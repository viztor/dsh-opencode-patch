/**
 * The pure half of `scripts/generate-go-limits.ts`: the text of
 * `src/go-limits-data.ts`, rendered from the allowance rows.
 *
 * A function of its rows, so `test/generators.test.ts` can render the shipped
 * `GO_MODEL_LIMITS`, run the formatter the nightly runs, and require the
 * committed file byte for byte: a template change that was not regenerated
 * fails the unit run, and the generator may then compare the rendered text
 * with the file to apply such a change with `--write`.
 *
 * @module scripts/go-limits-render
 */
import type { ModelAllowance } from "../src/go-limits.ts";

/**
 * A model id as an object key, quoted only when it has to be.
 *
 * `vp fmt` strips the quotes from any key that is a valid identifier, so a
 * uniformly-quoted generator produces a file that differs from its own
 * output by quoting alone, and the nightly's refresh would carry a diff that
 * is not a change.
 *
 * @param id - the model id.
 * @returns the key as TypeScript source.
 */
export const jsKey = (id: string): string =>
  /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(id) ? id : JSON.stringify(id);

/**
 * A number as TypeScript source.
 *
 * A model the vendor's page does not list has no published allowance, which the
 * table records as `NaN`. The bare `NaN` identifier is a lint error, so the
 * literal is written as `Number.NaN`; it stays `NaN` at runtime, which is the
 * point - a model with no figure must not read as `$0`.
 *
 * @param value - the allowance.
 * @returns the literal to emit.
 */
export const numberLiteral = (value: number): string =>
  Number.isNaN(value) ? "Number.NaN" : String(value);

/**
 * `src/go-limits-data.ts`, rendered: the header, the type import and one
 * entry per model, sorted by id, one field per line (what `vp fmt` produces
 * for an object this size, so the formatter has nothing to reflow).
 *
 * @param rows - the allowance per model id.
 * @returns the file's text.
 */
export const renderGoLimits = (
  rows: Readonly<Record<string, ModelAllowance>>
): string => {
  const entries = Object.entries(rows).toSorted(
    ([left], [right]) => Number(left > right) - Number(left < right)
  );
  const body = entries
    .map(([id, row]) =>
      [
        `  ${jsKey(id)}: {`,
        `    go: ${numberLiteral(row.go)},`,
        `    goPlus: ${numberLiteral(row.goPlus)},`,
        `    name: ${JSON.stringify(row.name)},`,
        "  },",
      ].join("\n")
    )
    .join("\n");
  return `/**
 * GENERATED by \`scripts/generate-go-limits.ts\` — do not edit by hand.
 *
 * The Go plan's monthly allowance per model, in whole US dollars, for both tiers:
 * \`go\` is the $10/month plan, \`goPlus\` the $40/month one. Source of truth is
 * OpenCode's own Go documentation; \`pnpm run limits:shim\` reports staleness and
 * \`--write\` rewrites this file.
 *
 * ${entries.length} models.
 */

import type { ModelAllowance } from "./go-limits.ts";

export const GO_MODEL_LIMITS: Readonly<Record<string, ModelAllowance>> = {
${body}
};
`;
};
